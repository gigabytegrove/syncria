func shellQuoted(value string)string{return "'"+strings.ReplaceAll(value,"'","'\\''")+"'"}
func psQuoted(value string)string{return "'"+strings.ReplaceAll(value,"'","''")+"'"}
func (a *App) computerBootstrapAPI(w http.ResponseWriter,r *http.Request){
 if r.Method!=http.MethodGet{computerError(w,405,"GET required");return}
 code:=r.URL.Query().Get("code")
 invitation,ok:=a.getComputerInvite(code)
 if !ok||invitation.State=="connected"{computerError(w,403,"Enrollment code expired or already used");return}
 hub:=strings.TrimSpace(r.URL.Query().Get("hub"))
 if err:=computerEnrollmentHubURL(hub);err!=nil{computerError(w,400,err.Error());return}
 parsed,_:=url.Parse(hub)
 // A proxy must preserve the public Host; never allow the code to turn this
 // installer into a third-party download or registration endpoint.
 if !strings.EqualFold(parsed.Host,r.Host){computerError(w,400,"Installer URL does not match the Syncria HTTPS hostname");return}
 platform:=r.URL.Query().Get("platform")
 var content string
 switch platform {
 case "windows":
  content=strings.NewReplacer("@@HUB@@",psQuoted(hub),"@@CODE@@",psQuoted(code)).Replace(windowsAgentBootstrap)
  w.Header().Set("Content-Type","text/plain; charset=utf-8")
 case "linux":
  content=strings.NewReplacer("@@HUB@@",shellQuoted(hub),"@@CODE@@",shellQuoted(code)).Replace(linuxAgentBootstrap)
  w.Header().Set("Content-Type","text/x-shellscript; charset=utf-8")
 default:computerError(w,400,"Supported installers: windows or linux");return
 }
 w.Header().Set("Cache-Control","no-store")
 w.Header().Set("X-Content-Type-Options","nosniff")
 w.Header().Set("Content-Disposition",fmt.Sprintf("attachment; filename=%q","syncria-install."+map[string]string{"windows":"ps1","linux":"sh"}[platform]))
 _,_=w.Write([]byte(content))
}

const windowsAgentBootstrap = `# Syncria self-hosted agent installer. Generated by YOUR Syncria server.
# Requires an HTTPS server with a trusted certificate.
$ErrorActionPreference = 'Stop'
$Hub = @@HUB@@
$Code = @@CODE@@
$Architecture = [System.Runtime.InteropServices.RuntimeInformation]::OSArchitecture.ToString().ToLowerInvariant()
if ($Architecture -eq 'x64') { $Asset = 'syncria-windows-amd64.exe' }
elseif ($Architecture -eq 'arm64') { $Asset = 'syncria-windows-arm64.exe' }
else { throw "Unsupported Windows CPU architecture: $Architecture" }
$Dir = Join-Path $env:LOCALAPPDATA 'Syncria\Agent'
$Identity = Join-Path $Dir 'identity'
$Shared = Join-Path $env:USERPROFILE 'Syncria Shared'
$Binary = Join-Path $Dir 'syncria-agent.exe'
$Stage = Join-Path $Dir 'syncria-agent.download'
New-Item -ItemType Directory -Force -Path $Dir,$Identity,$Shared | Out-Null
$PackageUrl = "$Hub/api/computers/asset?code=$Code&file=$Asset"
$ManifestUrl = "$Hub/api/computers/asset?code=$Code&file=SHA256SUMS"
Write-Host "Downloading verified Syncria agent from $Hub"
Invoke-WebRequest -Uri $PackageUrl -UseBasicParsing -OutFile $Stage
$Manifest = (Invoke-WebRequest -Uri $ManifestUrl -UseBasicParsing).Content
$Expected = ''
foreach ($Line in ($Manifest -split '\r?\n')) {
 $Parts = $Line.Trim() -split '\s+'
 if ($Parts.Count -eq 2 -and $Parts[1] -eq $Asset) { $Expected = $Parts[0].ToLowerInvariant() }
}
if ($Expected -notmatch '^[a-f0-9]{64}$') { throw 'Syncria release checksums were invalid' }
$Actual = (Get-FileHash -Path $Stage -Algorithm SHA256).Hash.ToLowerInvariant()
if ($Actual -ne $Expected) { Remove-Item -Force $Stage; throw 'Agent SHA256 does not match the release manifest' }
Move-Item -Force $Stage $Binary
# Token is only needed for first enrollment, and is erased by the agent on success.
@{hub=$Hub;code=$Code} | ConvertTo-Json | Set-Content -Path (Join-Path $Identity 'pending-enrollment.json') -Encoding UTF8
$DQ = [char]34
$Arguments = '-agent -listen 0.0.0.0:9765 -agent-data ' + $DQ + $Identity + $DQ + ' -agent-name ' + $DQ + $env:COMPUTERNAME + $DQ + ' -agent-root ' + $DQ + 'Files=' + $Shared + $DQ
$Startup = Join-Path $env:APPDATA 'Microsoft\Windows\Start Menu\Programs\Startup\Syncria Agent.lnk'
$Shell = New-Object -ComObject WScript.Shell
$Shortcut = $Shell.CreateShortcut($Startup)
$Shortcut.TargetPath = $Binary
$Shortcut.Arguments = $Arguments
$Shortcut.WorkingDirectory = $Dir
$Shortcut.WindowStyle = 7
$Shortcut.Save()
try {
 $RuleName = 'Syncria Agent LAN TCP 9765'
 $Existing = Get-NetFirewallRule -DisplayName $RuleName -ErrorAction SilentlyContinue
 if (-not $Existing) {
  New-NetFirewallRule -DisplayName $RuleName -Direction Inbound -Action Allow -Protocol TCP -LocalPort 9765 -RemoteAddress LocalSubnet -ErrorAction Stop | Out-Null
 }
 Write-Host 'Windows Firewall access limited to the local subnet.'
} catch { Write-Warning 'Could not set the Windows LAN firewall rule. If pairing fails, run this installer in an elevated PowerShell window.' }
Start-Process -FilePath $Binary -ArgumentList $Arguments -WorkingDirectory $Dir -WindowStyle Hidden
Write-Host 'Syncria agent installed and launched. It will pair automatically within seconds.'
Write-Host "Shared folder: $Shared"
Write-Host 'Starts automatically at Windows sign-in. Keep the computer signed in for background transfers.'
`

const linuxAgentBootstrap = `#!/usr/bin/env bash
# Syncria self-hosted agent installer — verified against SHA256SUMS.
set -Eeuo pipefail
HUB=@@HUB@@
CODE=@@CODE@@
case "$(uname -m)" in
 x86_64|amd64) ASSET="syncria-linux-amd64";;
 aarch64|arm64) ASSET="syncria-linux-arm64";;
 armv7l|armv6l) ASSET="syncria-linux-arm";;
 *) echo "Unsupported CPU architecture: $(uname -m)" >&2;exit 1;;
esac
BIN_DIR="$HOME/.local/bin"
BIN="$BIN_DIR/syncria-agent"
IDENTITY="$HOME/.local/share/syncria-agent/identity"
SHARED="$HOME/Syncria Shared"
mkdir -p "$BIN_DIR" "$IDENTITY" "$SHARED"
chmod 700 "$IDENTITY"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
echo "Downloading native agent from $HUB"
curl --fail --show-error --silent --location --retry 2 "$HUB/api/computers/asset?code=$CODE&file=$ASSET" -o "$TMP/$ASSET"
curl --fail --show-error --silent --location --retry 2 "$HUB/api/computers/asset?code=$CODE&file=SHA256SUMS" -o "$TMP/SHA256SUMS"
grep -F "  $ASSET" "$TMP/SHA256SUMS" > "$TMP/expected.sha256"
(cd "$TMP" && sha256sum -c expected.sha256)
install -m 700 "$TMP/$ASSET" "$BIN"
# Token is erased by the native agent after the hub verifies the connection.
printf '{"hub":"%s","code":"%s"}\n' "$HUB" "$CODE" > "$IDENTITY/pending-enrollment.json"
chmod 600 "$IDENTITY/pending-enrollment.json"
if command -v systemctl >/dev/null 2>&1 && systemctl --user show-environment >/dev/null 2>&1;then
 mkdir -p "$HOME/.config/systemd/user"
 cat > "$HOME/.config/systemd/user/syncria-agent.service" <<'UNIT'
[Unit]
Description=Syncria native file transfer agent
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
ExecStart=%h/.local/bin/syncria-agent -agent -listen 0.0.0.0:9765 -agent-data %h/.local/share/syncria-agent/identity -agent-name %H -agent-root "Files=%h/Syncria Shared"
Restart=on-failure
RestartSec=5

[Install]
WantedBy=default.target
UNIT
 systemctl --user daemon-reload
 systemctl --user enable --now syncria-agent.service
 echo 'Syncria systemd user agent installed and running.'
else
 nohup "$BIN" -agent -listen 0.0.0.0:9765 -agent-data "$IDENTITY" -agent-name "$(hostname)" -agent-root "Files=$SHARED" > "$IDENTITY/agent.log" 2>&1 < /dev/null &
 echo 'Syncria agent launched (user systemd is unavailable; startup persistence is not configured).'
fi
echo "Shared folder: $SHARED"
echo 'The agent will register automatically. If it cannot be reached, ensure LAN TCP 9765 is allowed.'
`
